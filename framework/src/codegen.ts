// Writes .optz/types.d.ts: your pages and API routes as types, so `<Link href>`, `PageProps`
// and `api()` are checked against the files that actually exist.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import type { Route } from "./routes";

export function writeTypes(root: string, pages: Route[], apis: Route[]) {
  const out = join(root, ".optz/types.d.ts");
  const params = (r: Route) => `{ ${r.segments.flatMap((s) => (s.kind === "static" ? [] : [`${s.name}${s.kind === "optional" ? "?" : ""}: string`])).join("; ")} }`;
  const imp = (f: string) => JSON.stringify(relative(dirname(out), f).replace(/\.(ts|tsx|js|jsx)$/, ""));
  const src = `// Generated by optz from app/routes and app/api. Don't edit; it's rewritten on every build.
import "optz/types";
declare module "optz/types" {
  interface RouteRegistry {
${pages.map((r) => `    ${JSON.stringify(r.pattern)}: ${params(r)};`).join("\n")}
  }
  interface ApiRegistry {
${apis.map((r) => `    ${JSON.stringify(r.pattern)}: typeof import(${imp(r.file)});`).join("\n")}
  }
}
export {};
`;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, src);
}
